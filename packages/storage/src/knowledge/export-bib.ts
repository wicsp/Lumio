import { mkdir, readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { Citekey, type NoteRef } from "@lumio/schema";
import { rewriteBibtexKey } from "@lumio/knowledge";
import { CoreError } from "@lumio/foundation";
import { parseFrontmatter } from "@lumio/knowledge";
import { entityDirectory } from "@lumio/knowledge";
import { scanVault } from "./vault.ts";
import { writeFileAtomic } from "./write.ts";

export interface BibExport { path: string; changed: boolean; count: number; warnings: string[] }

function bibtexBlock(body: string): string | undefined {
  let section = false;
  let fence: { character: string; length: number; bibtex: boolean } | undefined;
  let content: string[] = [];
  for (const line of body.split(/\r?\n/)) {
    const marker = /^ {0,3}(`{3,}|~{3,})(.*)$/.exec(line);
    if (fence) {
      if (marker && marker[1]![0] === fence.character && marker[1]!.length >= fence.length && !marker[2]!.trim()) {
        if (fence.bibtex) return content.join("\n").trim();
        fence = undefined;
      } else if (fence.bibtex) content.push(line);
      continue;
    }
    if (marker) {
      fence = { character: marker[1]![0]!, length: marker[1]!.length, bibtex: section && marker[2]!.trim().toLowerCase() === "bibtex" };
      content = [];
      continue;
    }
    const heading = /^ {0,3}(#{1,2})[ \t]+(.*)$/.exec(line);
    if (heading) section = heading[1] === "##" && heading[2]!.replace(/[ \t]+#+[ \t]*$/, "").trim().toLowerCase() === "bibtex";
  }
  return undefined;
}

/** Build the same bibliography for stdout and file exports. An empty selection exports no papers. */
export async function buildBib(root: string, papers?: readonly NoteRef[], msg: (key: string, ...args: unknown[]) => string = (key, ...args) => key.replace(/\$\{(\d+)\}/g, (_, index: string) => String(args[Number(index)]))): Promise<{ content: string; count: number; warnings: string[] }> {
  try {
    const entries: { key: string; path: string; text: string }[] = [];
    const warnings: string[] = [];
    const paths = papers === undefined ? undefined : new Set(papers.filter((p) => p.type === "paper").map((p) => p.path));
    for (const file of await scanVault(root, ["paper"])) {
      if (file.private || (paths && !paths.has(file.relativePath))) continue;
      const raw = await readFile(file.path);
      try {
        const { data, body } = parseFrontmatter(raw);
        if (!Citekey.safeParse(data.citekey).success) {
          warnings.push(msg("Missing valid citekey; skipped: ${0}", file.relativePath)); continue;
        }
        const original = bibtexBlock(body.toString("utf8"));
        if (original === undefined) { warnings.push(msg("Missing BibTeX section or code block; skipped: ${0}", file.relativePath)); continue; }
        const text = rewriteBibtexKey(original, data.citekey as string);
        if (text !== original) warnings.push(msg("BibTeX key corrected: ${0}", file.relativePath));
        entries.push({ key: data.citekey as string, path: file.relativePath, text });
      } catch (cause) {
        if (!(cause instanceof CoreError)) throw cause;
        warnings.push(msg("Could not parse frontmatter or BibTeX; skipped: ${0}", file.relativePath));
      }
    }
    entries.sort((a, b) => a.key < b.key ? -1 : a.key > b.key ? 1 : a.path < b.path ? -1 : 1);
    const content = msg("% Generated by lumio; do not edit manually\n\n${0}${1}", entries.map((e) => e.text).join("\n\n"), entries.length ? "\n" : "");
    return { content, count: entries.length, warnings };
  } catch (cause) {
    if (cause instanceof CoreError) throw cause;
    throw new CoreError("BIB_EXPORT_FAILED", { key: "export-bib.could_not_export_bibtex", args: [] }, { cause });
  }
}

export async function exportBib(root: string, out?: string, papers?: readonly NoteRef[], msg: (key: string, ...args: unknown[]) => string = (key, ...args) => key.replace(/\$\{(\d+)\}/g, (_, index: string) => String(args[Number(index)]))): Promise<BibExport> {
  try {
    const { content, count, warnings } = await buildBib(root, papers, msg);
    const path = out ?? join(root, entityDirectory("paper"), "..", "refs.bib");
    await mkdir(dirname(path), { recursive: true });
    const changed = await writeFileAtomic(path, Buffer.from(content));
    return { path, changed, count, warnings };
  } catch (cause) {
    if (cause instanceof CoreError) throw cause;
    throw new CoreError("BIB_EXPORT_FAILED", { key: "export-bib.could_not_export_bibtex", args: [] }, { cause });
  }
}
