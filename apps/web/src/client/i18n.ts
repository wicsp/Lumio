function stored(): Lang | undefined {
  try { const value = globalThis.localStorage?.getItem(KEY); return value === "en" || value === "zh" ? value : undefined; } catch { return undefined; }
}
function detected(): Lang {
  const languages = typeof navigator === "undefined" ? [] : [...(navigator.languages ?? []), navigator.language];
  return languages.some(value => typeof value === "string" && value.toLowerCase().startsWith("zh")) ? "zh" : "en";
}

let current: Lang = stored() ?? detected();
const listeners = new Set<(lang: Lang) => void>();

export const lang = (): Lang => current;
/** Intl 用的区域设置。 */
export const locale = (): string => current === "zh" ? "zh-CN" : "en-US";
/** 发给 Hub 的 Accept-Language（ADR 0028：Hub 据此选择错误说明的语言）。 */
export const acceptLanguage = (): string => current === "zh" ? "zh-CN,zh;q=0.9,en;q=0.5" : "en";

export function setLang(next: Lang, persist = true): void {
  if (persist) { try { globalThis.localStorage?.setItem(KEY, next); } catch { /* storage may be disabled */ } }
  if (next === current) return;
  current = next;
  const root = (globalThis as { document?: { documentElement: { lang: string } } }).document?.documentElement;
  if (root) root.lang = next === "zh" ? "zh-CN" : "en";
  for (const listener of listeners) listener(next);
}
export function onLang(listener: (lang: Lang) => void): () => void { listeners.add(listener); return () => listeners.delete(listener); }

const fill = (text: string, args: unknown[]) => text.replace(/\{(\d+)\}/g, (all, i: string) => Number(i) < args.length ? String(args[Number(i)]) : all);

/** 取当前语言的文案；中文表里没有时退回英文原文。 */
export function t(key: string, ...args: unknown[]): string {
  return fill(current === "zh" ? ZH[key] ?? key : key, args);
}

/** 句子里要嵌入 DOM 节点时用：按 {n} 切开，返回文字与节点交替的片段。 */
export function tParts<T>(key: string, ...parts: T[]): Array<string | T> {
  const text = current === "zh" ? ZH[key] ?? key : key;
  const out: Array<string | T> = [];
  let last = 0;
  for (const match of text.matchAll(/\{(\d+)\}/g)) {
    if (match.index! > last) out.push(text.slice(last, match.index));
    out.push(parts[Number(match[1])]!);
    last = match.index! + match[0].length;
  }
  if (last < text.length) out.push(text.slice(last));
  return out;
}

/** 文案随语言变化的对照表（例如状态名）：每次读取时翻译。 */
export function translated<K extends string>(table: Record<K, string>): Record<K, string> {
  return new Proxy(table, { get: (target, prop) => typeof prop === "string" && prop in target ? t(target[prop as K]) : undefined });
}
