export function text(key: string, ...args: unknown[]): string {
  return renderMessage((locale.getStore() ?? language()) === "zh" ? zh : en, { key, args });
}
export function errorMessage(cause: unknown): string {
  if (cause instanceof Error && "code" in cause && typeof cause.code === "string" && cause.code.startsWith("ERR_PARSE_ARGS_")) return text("arguments.invalid");
  if (cause && typeof cause === "object" && "params" in cause) return renderMessage((locale.getStore() ?? language()) === "zh" ? zh : en, (cause as { params: { key: string; args: readonly unknown[] } }).params);
  return cause instanceof Error ? cause.message : String(cause);
}

export function serviceText(key: string, ...args: unknown[]): string { return renderMessage(en, { key, args }); }
export function serviceErrorMessage(cause: unknown): string { return withLanguage("en", () => errorMessage(cause)); }
