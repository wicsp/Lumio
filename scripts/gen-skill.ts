import { readFile, writeFile } from "node:fs/promises";
import { CAPABILITIES } from "../packages/schema/src/index.ts";
import { CAPABILITY_COMMANDS } from "../skills/lumio/commands.ts";

export async function generateSkill(): Promise<string> {
  if (Object.keys(CAPABILITY_COMMANDS).length !== CAPABILITIES.length) throw new Error("Skill command catalog differs from CAPABILITIES");
  const rows = CAPABILITIES.map(capability => {
    const command = CAPABILITY_COMMANDS[capability.name];
    if (!command) throw new Error(`Missing CLI command: ${capability.name}`);
    return `| ${capability.name} | \`lumio ${command} --json\` | ${capability.summary.en} |`;
  });
  const source = await readFile(new URL("../skills/lumio/instructions.md", import.meta.url), "utf8");
  return source.replace("<!-- commands -->", ["<!-- Generated by bun run gen:skill. Edit instructions.md or commands.ts. -->", "| Capability | Command | Purpose |", "|---|---|---|", ...rows].join("\n"));
}
if (import.meta.main) await writeFile(new URL("../skills/lumio/SKILL.md", import.meta.url), await generateSkill());
